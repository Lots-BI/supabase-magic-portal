function Glyph({ d, className, title }: { d: string; className?: string; title?: string }) {
  return (
    <svg viewBox="0 0 24 24" className={className} aria-hidden fill="currentColor">
      {title ? <title>{title}</title> : null}
      <path d={d} />
    </svg>
  );
}

export function PlatformBrandMark({
  dashboardId,
  className,
  decorative = true,
}: {
  dashboardId: string;
  className?: string;
  decorative?: boolean;
}) {
  const markKey = CATALOG_TO_MARK[dashboardId] ?? "instagram";
  const d = MARK_PATH[markKey];

  if (markKey === "tiktok" && !decorative) {
    return (
      <span className={cn("relative inline-grid", className)} aria-hidden>
        <Glyph
          d={d}
          className="col-start-1 row-start-1 h-full w-full -translate-x-[1.5px] text-[#25F4EE]"
        />
        <Glyph
          d={d}
          className="col-start-1 row-start-1 h-full w-full translate-x-[1.5px] text-[#FE2C55]"
        />
        <Glyph d={d} className="col-start-1 row-start-1 h-full w-full text-white" />
      </span>
    );
  }

  return <Glyph d={d} className={className} />;
}

